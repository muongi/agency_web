function rebuildCommonFile(array $en, array $existing, array $overlays, string $path): void
{
    $merged = array_merge($existing, $overlays);
    $lines = ["<?php\n", "\n", "return [\n"];

    foreach ($en as $key => $value) {
        if (!isset($merged[$key])) {
            fwrite(STDERR, "WARNING: missing translation for key '$key' in $path\n");
            $merged[$key] = $value;
        }
        $escaped = str_replace("'", "\\'", $merged[$key]);
        $lines[] = "    '$key' => '$escaped',\n";
    }

    foreach (array_diff_key($merged, $en) as $key => $value) {
        $escaped = str_replace("'", "\\'", $value);
        $lines[] = "    '$key' => '$escaped',\n";
    }

    $lines[] = "];\n";
    file_put_contents($path, implode('', $lines));
}

